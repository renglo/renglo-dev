def render_launcher(*, profile: str, region: str, config_path: Path) -> str:
    return "\n".join(
        [
            "# AWS profile for the local API. renglo reads this file when it starts the API.",
            "# Edit the profile here if this machine should use a different one.",
            f"AWS_PROFILE={_sh(profile)}",
            f"AWS_DEFAULT_REGION={_sh(region)}",
            f"RENGLO_CONFIG_PATH={_sh(str(config_path))}",
            "",
        ]
    )


def placeholder_keys(text: str, keys: tuple[str, ...]) -> list[str]:
    values = _assignments(text)
    found = []
    for key in keys:
        if values.get(key, "") in _PLACEHOLDER_VALUES:
            found.append(key)
    return found


def print_handoff(report: ConfigReport) -> None:
    print()
    print("Config files")
    for path in report.wrote:
        print(f"  wrote  {path}")
    for path in report.kept:
        print(f"  kept   {path}")
    for path in report.missing:
        print(f"  missing  {path}")
    print()
    print("Put the operator's env_config.py and .env.development at the paths above when you have them.")
    print("Files that are already there are left as they are, including SECRET_KEY and CSRF_SESSION_KEY.")
    print("The AWS profile and region used at launch are in renglo-dev/.env.launcher.")
    any_placeholder = False
    for path, keys in report.placeholders.items():
        if not keys:
            continue
        any_placeholder = True
        print(f"  still placeholders in {path}:")
        print("    " + ", ".join(keys))
    if not any_placeholder and not report.missing:
        print("  No placeholder keys left in the local config.")
    print()


def _ensure(report: ConfigReport, path: Path, render, *, ready: bool) -> None:
    label = str(path)
    if path.is_file():
        report.kept.append(label)
        return
    if not ready:
        report.missing.append(label)
        return
    path.write_text(render(), encoding="utf-8")
    report.wrote.append(label)


def _assignments(text: str) -> dict[str, str]:
    values: dict[str, str] = {}
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        match = _ASSIGN.match(line)
        if not match:
            continue
        values[match.group(1)] = _rhs(match.group(2))
    return values


def _rhs(raw: str) -> str:
    text = raw.split("#", 1)[0].strip()
    if len(text) >= 2 and text[0] == text[-1] and text[0] in "'\"":
        return text[1:-1]
    return text


def _py(value: str) -> str:
    return repr(value)


def _sh(value: str) -> str:
    return "'" + value.replace("'", "'\"'\"'") + "'"
